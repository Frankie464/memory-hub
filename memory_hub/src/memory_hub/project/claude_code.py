"""Generate CLAUDE.md additions and rules files for Claude Code."""
from datetime import datetime
from pathlib import Path

from memory_hub.config import (
    CLAUDE_MD_BEGIN,
    CLAUDE_MD_END,
    CLAUDE_MD_PATH,
    CLAUDE_RULES_DIR,
    DB_PATH,
    PROFILE_MANUAL_PATH,
    PROJ_CLAUDE_CODE,
)
from memory_hub.db import get_connection, get_active_facts_as_dicts, get_statements, record_projections, sanitize_statement


def _build_claude_md_block(facts: list) -> str:
    identity = get_statements(facts, "identity")
    prefs = get_statements(facts, "preference")
    work = get_statements(facts, "work")
    interests = get_statements(facts, "interest")

    lines = [
        CLAUDE_MD_BEGIN,
        "",
        "# About the user",
        "## Identity",
    ]
    for s in identity[:6]:
        lines.append(f"- {s}")
    lines += ["", "## Communication Style"]
    for s in prefs[:8]:
        lines.append(f"- {s}")
    lines += ["", "## Professional"]
    for s in work[:6]:
        lines.append(f"- {s}")
    lines += ["", "## Key Domains"]
    for s in interests[:10]:
        lines.append(f"- {s}")
    lines += [
        "",
        "## Available MCP: ChatGPT History",
        "- chatgpt-history MCP server can search all past ChatGPT conversations",
        "- Use search_conversations when past context about the user's projects would help",
        "",
        CLAUDE_MD_END,
    ]
    return "\n".join(lines)


def _build_personal_context(facts: list) -> str:
    relationships = get_statements(facts, "relationship")
    lifestyle = get_statements(facts, "lifestyle")
    financial = get_statements(facts, "financial")

    now = datetime.now().strftime("%Y-%m-%d")
    lines = [
        f"# Personal Context (generated {now})",
        "# Auto-generated by memory-hub — edit user_profile.manual.md to customize",
        "",
        "## Relationships",
    ]
    for s in relationships:
        lines.append(f"- {s}")
    lines += ["", "## Lifestyle"]
    for s in lifestyle:
        lines.append(f"- {s}")
    lines += ["", "## Financial Framework"]
    for s in financial:
        lines.append(f"- {s}")
    return "\n".join(lines)


def _build_work_domain(facts: list) -> str:
    work = get_statements(facts, "work")
    now = datetime.now().strftime("%Y-%m-%d")
    lines = [
        f"# RF Engineering Context (generated {now})",
        "# Auto-generated by memory-hub",
        "",
        "## Work Domain",
        "- the user is an Software Engineer at Acme",
        "- Works with [vendor] VNAs (M937x), 4-port ECal, [protocol] test flows",
        "- S-parameter analysis, Smith charts, VSWR calculations",
        "- Python and Excel automation for RF test data extraction",
        "",
        "## Learning Goals",
        "- Deepening RF fundamentals ([textbook] Microwave Engineering as primary text)",
        "- Building interactive RF coursework and simulation tools",
        "",
        "## Workflow Preferences",
        "- Python scripts with progress bars and restart-from-checkpoint support",
        "- Interactive tools with dark mode",
        "- Detailed step-by-step instructions with templates and naming conventions",
        "- Downloadable/shareable outputs (ZIPs, repos, interactive HTML)",
    ]
    for s in work:
        if f"- {s}" not in lines:
            lines.append(f"- {s}")
    return "\n".join(lines)


def project_claude_code(deploy: bool = False, db_path: Path = DB_PATH) -> dict[str, Path]:
    """
    Generate Claude Code projection files.
    If deploy=True, writes to ~/.claude/ locations (with marker-block safety for CLAUDE.md).
    Returns dict of {name: path} for generated files.
    """
    PROJ_CLAUDE_CODE.mkdir(parents=True, exist_ok=True)

    with get_connection(db_path) as conn:
        facts = get_active_facts_as_dicts(conn)

    claude_md_block = _build_claude_md_block(facts)
    personal_ctx = _build_personal_context(facts)
    rf_eng = _build_work_domain(facts)

    out_files = {}

    # Write to projections dir
    additions_path = PROJ_CLAUDE_CODE / "CLAUDE_additions.md"
    personal_path = PROJ_CLAUDE_CODE / "personal-context.md"
    rf_path = PROJ_CLAUDE_CODE / "work-domain.md"

    additions_path.write_text(claude_md_block, encoding="utf-8")
    personal_path.write_text(personal_ctx, encoding="utf-8")
    rf_path.write_text(rf_eng, encoding="utf-8")

    out_files = {
        "CLAUDE_additions": additions_path,
        "personal-context": personal_path,
        "work-domain": rf_path,
    }

    if deploy:
        # Deploy CLAUDE.md using marker blocks
        _deploy_claude_md(claude_md_block)
        # Deploy rules files (full overwrite — these are fully generated)
        CLAUDE_RULES_DIR.mkdir(parents=True, exist_ok=True)
        (CLAUDE_RULES_DIR / "personal-context.md").write_text(personal_ctx, encoding="utf-8")
        (CLAUDE_RULES_DIR / "work-domain.md").write_text(rf_eng, encoding="utf-8")

    with get_connection(db_path) as conn:
        record_projections(conn, "claude_code", out_files)

    return out_files


def _deploy_claude_md(block: str) -> None:
    """Insert or replace the MEMORY_HUB block in ~/.claude/CLAUDE.md."""
    CLAUDE_MD_PATH.parent.mkdir(parents=True, exist_ok=True)

    if CLAUDE_MD_PATH.exists():
        existing = CLAUDE_MD_PATH.read_text(encoding="utf-8")
        if CLAUDE_MD_BEGIN in existing and CLAUDE_MD_END in existing:
            # Replace existing block
            before = existing[: existing.index(CLAUDE_MD_BEGIN)]
            after = existing[existing.index(CLAUDE_MD_END) + len(CLAUDE_MD_END):]
            new_content = before.rstrip() + "\n\n" + block + "\n" + after.lstrip()
        else:
            # Append block at end
            new_content = existing.rstrip() + "\n\n" + block + "\n"
    else:
        new_content = block + "\n"

    CLAUDE_MD_PATH.write_text(new_content, encoding="utf-8")
